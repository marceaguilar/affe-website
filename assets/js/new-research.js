/* ==========================================================================
   New Research page
   Reads the pre-built, pre-verified feed at /assets/data/new-research.json
   and renders it with client-side search, filters and sorting.

   The feed is generated by tools/new-research/build.py. This file never
   talks to an external API, so the page stays fast and cannot break when a
   third-party service is down.
   ========================================================================== */

(function () {
  'use strict';

  var PAGE_SIZE = 25;

  var state = {
    papers: [],
    filtered: [],
    shown: PAGE_SIZE,
    query: '',
    discipline: 'all',
    venue_kind: 'all',
    window: 'all',
    sort: 'newest'
  };

  var els = {};

  document.addEventListener('DOMContentLoaded', init);

  function init() {
    var root = document.getElementById('new-research');
    if (!root) return;

    els.root = root;
    els.list = document.getElementById('nr-list');
    els.status = document.getElementById('nr-status');
    els.empty = document.getElementById('nr-empty');
    els.more = document.getElementById('nr-more');
    els.search = document.getElementById('nr-q');
    els.sort = document.getElementById('nr-sort');
    els.generated = document.getElementById('nr-generated');

    bindControls();
    loadFeed(root.getAttribute('data-feed'));
  }

  /* ------------------------------------------------------------- loading */

  function loadFeed(url) {
    fetch(url, { cache: 'no-cache' })
      .then(function (response) {
        if (!response.ok) throw new Error('HTTP ' + response.status);
        return response.json();
      })
      .then(function (data) {
        state.papers = (data && data.papers) || [];
        showGeneratedStamp(data);
        applyFilters();
      })
      .catch(function (error) {
        els.status.className = 'nr-status is-error';
        els.status.textContent =
          'The research feed could not be loaded (' + error.message + '). ' +
          'Please try again later or email affe-committee@googlegroups.com.';
      });
  }

  function showGeneratedStamp(data) {
    if (!els.generated || !data || !data.generated) return;
    var when = new Date(data.generated);
    if (isNaN(when.getTime())) return;
    els.generated.textContent =
      'Last updated ' +
      when.toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' }) +
      '. ';
  }

  /* ------------------------------------------------------------ controls */

  function bindControls() {
    Array.prototype.forEach.call(els.root.querySelectorAll('.nr-chips'), function (group) {
      var key = group.getAttribute('data-filter');
      group.addEventListener('click', function (event) {
        var chip = event.target.closest('.nr-chip');
        if (!chip || !group.contains(chip)) return;
        Array.prototype.forEach.call(group.querySelectorAll('.nr-chip'), function (other) {
          other.classList.toggle('is-active', other === chip);
        });
        state[key] = chip.getAttribute('data-value');
        state.shown = PAGE_SIZE;
        applyFilters();
      });
    });

    els.search.addEventListener('input', debounce(function () {
      state.query = els.search.value.trim().toLowerCase();
      state.shown = PAGE_SIZE;
      applyFilters();
    }, 180));

    els.sort.addEventListener('change', function () {
      state.sort = els.sort.value;
      applyFilters();
    });

    els.more.addEventListener('click', function () {
      state.shown += PAGE_SIZE;
      render();
    });

    document.getElementById('nr-reset').addEventListener('click', resetFilters);
  }

  function resetFilters() {
    state.query = '';
    state.discipline = 'all';
    state.venue_kind = 'all';
    state.window = 'all';
    state.shown = PAGE_SIZE;
    els.search.value = '';
    Array.prototype.forEach.call(els.root.querySelectorAll('.nr-chips'), function (group) {
      Array.prototype.forEach.call(group.querySelectorAll('.nr-chip'), function (chip) {
        chip.classList.toggle('is-active', chip.getAttribute('data-value') === 'all');
      });
    });
    applyFilters();
  }

  /* ------------------------------------------------------------ filtering */

  function applyFilters() {
    var cutoff = null;
    if (state.window !== 'all') {
      cutoff = new Date();
      cutoff.setDate(cutoff.getDate() - parseInt(state.window, 10));
    }

    state.filtered = state.papers.filter(function (paper) {
      if (state.discipline !== 'all' && paper.discipline !== state.discipline) return false;
      if (state.venue_kind !== 'all' && paper.venue_kind !== state.venue_kind) return false;
      if (cutoff) {
        var posted = paper.date ? new Date(paper.date) : null;
        if (!posted || isNaN(posted.getTime()) || posted < cutoff) return false;
      }
      if (state.query && haystack(paper).indexOf(state.query) === -1) return false;
      return true;
    });

    sortPapers(state.filtered);
    render();
  }

  function haystack(paper) {
    if (!paper._haystack) {
      paper._haystack = [
        paper.title,
        (paper.authors || []).join(' '),
        paper.summary,
        paper.venue,
        paper.venue_short,
        paper.discipline,
        paper.year
      ].join(' ').toLowerCase();
    }
    return paper._haystack;
  }

  function sortPapers(list) {
    var newestFirst = state.sort !== 'oldest';
    list.sort(function (a, b) {
      if (state.sort === 'title') {
        return (a.title || '').localeCompare(b.title || '');
      }
      if (state.sort === 'cited') {
        return (b.cited_by_count || 0) - (a.cited_by_count || 0);
      }
      // ISO dates sort correctly as strings. Papers with only a year fall
      // back to the year, which sorts before any dated paper in that year.
      var left = a.date || String(a.year || '');
      var right = b.date || String(b.year || '');
      if (left === right) return 0;
      if (newestFirst) return left < right ? 1 : -1;
      return left < right ? -1 : 1;
    });
  }

  /* ------------------------------------------------------------ rendering */

  function render() {
    var total = state.filtered.length;
    var visible = state.filtered.slice(0, state.shown);

    els.list.innerHTML = '';
    visible.forEach(function (paper) {
      els.list.appendChild(buildCard(paper));
    });

    els.status.className = 'nr-status';
    els.status.textContent = total === 0
      ? ''
      : 'Showing ' + visible.length + ' of ' + total +
        (total === 1 ? ' verified paper' : ' verified papers') +
        (state.papers.length !== total ? ' (' + state.papers.length + ' in the feed)' : '');

    els.empty.hidden = total !== 0;
    els.more.hidden = visible.length >= total;
  }

  function buildCard(paper) {
    var item = document.createElement('li');
    item.className = 'nr-item';
    item.setAttribute('data-discipline', paper.discipline || '');

    var head = document.createElement('div');
    head.className = 'nr-item-head';

    var year = document.createElement('span');
    year.className = 'nr-year';
    year.textContent = paper.year || '';
    head.appendChild(year);

    var title = document.createElement('h3');
    title.className = 'nr-title';
    if (paper.url) {
      var link = document.createElement('a');
      link.href = paper.url;
      link.target = '_blank';
      link.rel = 'noopener noreferrer';
      highlightInto(link, paper.title || 'Untitled');
      title.appendChild(link);
    } else {
      highlightInto(title, paper.title || 'Untitled');
    }
    head.appendChild(title);
    item.appendChild(head);

    var authors = document.createElement('p');
    authors.className = 'nr-authors';
    highlightInto(authors, formatAuthors(paper.authors));
    item.appendChild(authors);

    if (paper.summary) {
      var summary = document.createElement('p');
      summary.className = 'nr-summary' +
        (paper.summary_source === 'metadata' ? ' is-metadata' : '');
      highlightInto(summary, paper.summary);
      item.appendChild(summary);
    }

    item.appendChild(buildBadges(paper));
    return item;
  }

  function buildBadges(paper) {
    var badges = document.createElement('div');
    badges.className = 'nr-badges';

    var venue = document.createElement('span');
    venue.className = 'nr-badge ' + (paper.venue_kind === 'ssrn' ? 'nr-badge-ssrn' : 'nr-badge-venue');
    venue.textContent = paper.venue_kind === 'ssrn' ? 'SSRN working paper' : paper.venue;
    badges.appendChild(venue);

    if (paper.discipline) {
      var field = document.createElement('span');
      field.className = 'nr-badge nr-badge-field';
      field.textContent = paper.discipline;
      badges.appendChild(field);
    }

    var verified = (paper.verified_in || []);
    if (verified.length >= 2) {
      var check = document.createElement('span');
      check.className = 'nr-badge nr-badge-verified';
      check.title = 'DOI and title confirmed in ' + verified.join(' and ');
      check.innerHTML =
        '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="3" ' +
        'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">' +
        '<polyline points="20 6 9 17 4 12"></polyline></svg>Verified';
      badges.appendChild(check);
    }

    if (paper.cited_by_count) {
      var cited = document.createElement('span');
      cited.className = 'nr-badge nr-badge-cited';
      cited.textContent = paper.cited_by_count +
        (paper.cited_by_count === 1 ? ' citation' : ' citations');
      badges.appendChild(cited);
    }

    if (paper.doi) {
      var doi = document.createElement('a');
      doi.className = 'nr-doi';
      doi.href = paper.url;
      doi.target = '_blank';
      doi.rel = 'noopener noreferrer';
      doi.textContent = 'doi:' + paper.doi;
      badges.appendChild(doi);
    }

    return badges;
  }

  function formatAuthors(authors) {
    if (!authors || !authors.length) return 'Author not listed';
    if (authors.length <= 6) return authors.join(', ');
    return authors.slice(0, 6).join(', ') + ', and ' + (authors.length - 6) + ' more';
  }

  /* --------------------------------------------------------------- search */

  // Writes `text` into `node`, wrapping matches of the current query in
  // <mark>. Built from text nodes rather than innerHTML so feed content is
  // never interpreted as markup.
  function highlightInto(node, text) {
    text = text == null ? '' : String(text);
    if (!state.query) {
      node.appendChild(document.createTextNode(text));
      return;
    }
    var lowered = text.toLowerCase();
    var needle = state.query;
    var cursor = 0;
    var found = lowered.indexOf(needle);
    while (found !== -1) {
      if (found > cursor) {
        node.appendChild(document.createTextNode(text.slice(cursor, found)));
      }
      var mark = document.createElement('mark');
      mark.className = 'nr-hit';
      mark.textContent = text.slice(found, found + needle.length);
      node.appendChild(mark);
      cursor = found + needle.length;
      found = lowered.indexOf(needle, cursor);
    }
    if (cursor < text.length) {
      node.appendChild(document.createTextNode(text.slice(cursor)));
    }
  }

  function debounce(fn, wait) {
    var timer;
    return function () {
      clearTimeout(timer);
      timer = setTimeout(fn, wait);
    };
  }
})();
